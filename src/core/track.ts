function formatRelevantFiles(files: TrackRelevantFile[], scan: ScanResult): string {
  if (!files.length) {
    return '_No existing files matched this feature. Treat it as a greenfield area, but still scan for reusable utilities before adding new ones._';
  }
  const byPath = new Map(scan.files.map((file) => [file.path, file]));
  return files
    .map((file) => {
      const info = byPath.get(file.path);
      const exports = info?.exports.length
        ? ` Exports: ${info.exports.slice(0, 10).join(', ')}.`
        : '';
      const reasons = file.reasons.length ? ` Why: ${file.reasons.join('; ')}.` : '';
      return `- \`${file.path}\` (${info?.lines ?? '?'} lines).${exports}${reasons}`;
    })
    .join('\n');
}

function formatScanFindings(files: TrackRelevantFile[], scan: ScanResult): string {
  const byPath = new Map(scan.files.map((file) => [file.path, file]));
  const lines: string[] = [];
  lines.push(
    `- Scanned ${scan.stats.files} files (${scan.stats.sourceFiles} source, ${scan.stats.totalLines} total lines).`,
  );
  const focusSet = new Set(files.map((file) => file.path));
  const relevantBloated = scan.bloatedFiles.filter((file) => focusSet.has(file.path));
  if (relevantBloated.length) {
    lines.push(
      `- Relevant files already over the ${scan.limits.maxFileLines}-line limit: ${relevantBloated
        .map((file) => `\`${file.path}\` (${file.lines} lines)`)
        .join(', ')}. Extract rather than extend if this track must touch them.`,
    );
  }
  const relevantLong = scan.longFunctions.filter((fn) => focusSet.has(fn.path)).slice(0, 5);
  for (const fn of relevantLong) {
    lines.push(
      `- Long function candidate: \`${fn.name}\` in \`${fn.path}:${fn.startLine}\` (${fn.lineCount} lines).`,
    );
  }
  const exports = files.flatMap((file) => byPath.get(file.path)?.exports ?? []).slice(0, 30);
  if (exports.length)
    lines.push(
      `- Existing symbols to reuse or extend: ${exports.map((s) => `\`${s}\``).join(', ')}.`,
    );
  if (!files.length)
    lines.push(
      '- No focused matches. Confirm there is no existing implementation before adding new modules.',
    );
  if (scan.orphans.length) {
    lines.push(
      `- ${scan.orphans.length} possibly orphaned file(s) detected. Do not delete them as part of this track; confirm separately.`,
    );
  }
  lines.push(
    '- Human-reviewed code map: `.specvibe/context/codebase-summary.md` is regenerated by init/scan.',
  );
  return lines.join('\n');
}

function buildGates(commands: Record<string, string | undefined>): string {
  const gates: string[] = [];
  let index = 1;
  if (commands.build) {
    gates.push(`- [ ] G${index++} — Build passes: \`${commands.build}\``);
  }
  if (commands.test) {
    gates.push(`- [ ] G${index++} — Tests pass: \`${commands.test}\``);
  }
  if (commands.typecheck) {
    gates.push(`- [ ] G${index++} — Typecheck passes: \`${commands.typecheck}\``);
  }
  if (commands.lint) {
    gates.push(`- [ ] G${index++} — Lint passes: \`${commands.lint}\``);
  }
  gates.push(
    `- [ ] G${index++} — Acceptance walkthrough: every acceptance criterion in \`spec.md\` is demonstrated or evidenced.`,
  );
  return gates.join('\n');
}

function buildImplementationTasks(): string {
  return [
    '- [ ] T1 — [NEEDS CLARIFICATION: describe the smallest end-to-end vertical slice and the files it touches]',
    '- [ ] T2 — [NEEDS CLARIFICATION: describe the focused tests that prove the behavior]',
    '- [ ] T3 — [NEEDS CLARIFICATION: describe integration, cleanup, and documentation work]',
  ].join('\n');
}

function buildCompletionTasks(): string {
  return [
    '- [ ] C1 — All acceptance criteria in `spec.md` are checked and verified.',
    '- [ ] C2 — Constitution limits are respected: no oversized files, no forbidden patterns, no new dependencies without a decision.',
    '- [ ] C3 — Existing code was reused or extended where possible; duplication was checked against the codebase map.',
  ].join('\n');
}

export async function trackExists(root: string, slug: string): Promise<boolean> {
  return pathExists(trackDir(root, slug));
}

export async function readTrackMeta(root: string, slug: string): Promise<TrackMeta> {
  const file = trackFiles(root, slug).meta;
  if (!(await pathExists(file))) {
    throw new SpecVibeError('TRACK_NOT_FOUND', `Track "${slug}" does not exist.`, {
      hint: 'Run `specvibe status` to list tracks.',
    });
  }
  try {
    const meta = JSON.parse(await readText(file)) as TrackMeta;
    if (meta?.version !== 1 || typeof meta.slug !== 'string') {
      throw new Error('invalid meta');
    }
    return meta;
  } catch (error) {
    throw new SpecVibeError('CONFIG', `Track metadata is unreadable: ${file}`, { cause: error });
  }
}

export async function writeTrackMeta(root: string, meta: TrackMeta): Promise<void> {
  await writeJson(trackFiles(root, meta.slug).meta, meta);
}

export async function updateTrackMeta(
  root: string,
  slug: string,
  patch: Partial<TrackMeta>,
): Promise<TrackMeta> {
  const meta = await readTrackMeta(root, slug);
  const next: TrackMeta = { ...meta, ...patch, slug: meta.slug, updatedAt: nowIso() };
  await writeTrackMeta(root, next);
  return next;
}

export async function listTracks(root: string): Promise<TrackMeta[]> {
  const paths = projectPaths(root);
  const entries = await listDirectory(paths.tracks);
  const tracks: TrackMeta[] = [];
  for (const entry of entries) {
    try {
      const meta = await readTrackMeta(root, entry);
      tracks.push(meta);
    } catch {
      // Ignore incomplete directories so one bad track cannot break status.
    }
  }
  return tracks.sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));
}

export async function resolveTrack(
  root: string,
  query?: string,
): Promise<{ meta: TrackMeta; slug: string }> {
  const tracks = await listTracks(root);
  const activeSlug = (await loadState(root)).activeTrack;
  if (!query) {
    if (activeSlug) {
      const active = tracks.find((track) => track.slug === activeSlug);
      if (active) return { meta: active, slug: active.slug };
    }
    if (tracks.length === 1 && tracks[0]) return { meta: tracks[0], slug: tracks[0].slug };
    throw new SpecVibeError('TRACK_NOT_FOUND', 'No active track was specified.', {
      hint: tracks.length
        ? `Available tracks: ${tracks.map((track) => track.slug).join(', ')}.`
        : 'Create one with `specvibe propose "<feature>"`.',
    });
  }

  const normalized = query.toLowerCase();
  const exact = tracks.filter((track) => track.slug.toLowerCase() === normalized);
  if (exact.length === 1 && exact[0]) return { meta: exact[0], slug: exact[0].slug };
  const prefixed = tracks.filter((track) => track.slug.toLowerCase().startsWith(normalized));
  if (prefixed.length === 1 && prefixed[0]) return { meta: prefixed[0], slug: prefixed[0].slug };
  const contains = tracks.filter((track) => track.slug.toLowerCase().includes(normalized));
  if (contains.length === 1 && contains[0]) return { meta: contains[0], slug: contains[0].slug };
  if (contains.length > 1) {
    throw new SpecVibeError('TRACK_NOT_FOUND', `Track name "${query}" is ambiguous.`, {
      hint: `Matches: ${contains.map((track) => track.slug).join(', ')}.`,
    });
  }
  throw new SpecVibeError('TRACK_NOT_FOUND', `Track "${query}" does not exist.`, {
    hint: tracks.length
      ? `Available tracks: ${tracks.map((track) => track.slug).join(', ')}.`
      : 'Create one with `specvibe propose "<feature>"`.',
  });
}

export async function createTrack(options: CreateTrackOptions): Promise<TrackMeta> {
  const { root, title, slug, config, scan, projectName, stack, commands } = options;
  if (await trackExists(root, slug)) {
    throw new SpecVibeError('TRACK_EXISTS', `Track "${slug}" already exists.`, {
      hint: 'Choose a different feature name or finish the existing track first.',
    });
  }
  const paths = trackFiles(root, slug);
  await ensureDir(paths.dir);
  const relevantFiles: TrackRelevantFile[] = (scan.focus ?? []).map((file) => ({
    path: file.path,
    score: file.score,
    reasons: file.reasons,
  }));
  const gates = buildGates(commands);
  const implementation = buildImplementationTasks();
  const completion = buildCompletionTasks();
  const common = {
    TITLE: title,
    SLUG: slug,
    DATE: today(),
    TIMESTAMP: nowIso(),
    PROJECT_NAME: projectName,
    STACK: stack.join(', ') || 'Unknown',
    MAX_FILE_LINES: config.maxFileLines,
    MAX_FUNCTION_LINES: config.maxFunctionLines,
    CONSTITUTION_PATH: '.specvibe/constitution.md',
    CONTEXT_PATH: '.specvibe/context.md',
    SUMMARY_PATH: '.specvibe/context/codebase-summary.md',
    RELEVANT_FILES: formatRelevantFiles(relevantFiles, scan),
    SCAN_FINDINGS: formatScanFindings(relevantFiles, scan),
    IMPLEMENTATION_TASKS: implementation,
    VERIFICATION_GATES: gates,
    COMPLETION_TASKS: completion,
    BUILD_COMMAND: commands.build ?? 'the project build command',
    TEST_COMMAND: commands.test ?? 'the project test command',
    LINT_COMMAND: commands.lint ?? 'the project lint command',
  };

  const docs: Array<[string, string]> = [
    [paths.proposal, 'tracks/proposal.md'],
    [paths.spec, 'tracks/spec.md'],
    [paths.design, 'tracks/design.md'],
    [paths.tasks, 'tracks/tasks.md'],
  ];
  for (const [file, template] of docs) {
    await writeText(file, await renderTemplate(template, common));
  }

  const baseCommit = (await isGitRepo(root))
    ? await getHead(root).catch(() => undefined)
    : undefined;
  const meta: TrackMeta = {
    version: 1,
    slug,
    title,
    status: 'proposed',
    createdAt: nowIso(),
    updatedAt: nowIso(),
    relevantFiles,
    baseCommit,
  };
  await writeTrackMeta(root, meta);
  await appendHistory(root, {
    event: 'proposed',
    track: slug,
    detail: title,
  });
  return meta;
}

export async function readTrackDocuments(
  root: string,
  slug: string,
): Promise<{
  proposal: string;
  spec: string;
  design: string;
  tasks: string;
}> {
  const paths = trackFiles(root, slug);
  const [proposal, spec, design, tasks] = await Promise.all([
    readText(paths.proposal, ''),
    readText(paths.spec, ''),
    readText(paths.design, ''),
    readText(paths.tasks, ''),
  ]);
  return { proposal, spec, design, tasks };
}

export function getTrackProgress(spec: string, tasks: string): TrackProgress {
  const allTasks = parseChecklist(tasks).filter(
    (item) => item.kind !== 'acceptance' && item.kind !== 'decision',
  );
  const tasksOnly = allTasks.filter((item) => item.kind === 'task');
  const gates = allTasks.filter((item) => item.kind === 'gate');
  const completion = allTasks.filter((item) => item.kind === 'completion');
  const acceptance = parseChecklist(spec, 'Acceptance Criteria');
  const completed = allTasks.filter((item) => item.checked).length;
  return {
    tasks: tasksOnly,
    gates,
    completion,
    acceptance,
    allTasks,
    next: allTasks.find((item) => !item.checked) ?? null,
    total: allTasks.length,
    completed,
    percent: allTasks.length ? Math.round((completed / allTasks.length) * 100) : 0,
  };
}

export async function getTrackProgressFromDisk(root: string, slug: string): Promise<TrackProgress> {
  const docs = await readTrackDocuments(root, slug);
  return getTrackProgress(docs.spec, docs.tasks);
}

export async function toggleTask(
  root: string,
  slug: string,
  id: string,
  options: { force?: boolean; confirmGate?: boolean } = {},
): Promise<{ item: ChecklistItem; progress: TrackProgress; next: ChecklistItem | null }> {
  const paths = trackFiles(root, slug);
  const tasks = await readText(paths.tasks, '');
  const progress = getTrackProgress(await readText(paths.spec, ''), tasks);
  const target = progress.allTasks.find((item) => item.id?.toUpperCase() === id.toUpperCase());
  if (!target) {
    throw new SpecVibeError('USAGE', `Task "${id}" was not found in tasks.md.`, {
      hint: progress.next ? `Next unchecked item: ${progress.next.id ?? 'unnumbered'}.` : undefined,
    });
  }
  if (target.checked) {
    return { item: target, progress, next: progress.next };
  }
  if (target.kind === 'gate' && !options.confirmGate) {
    throw new SpecVibeError(
      'INVALID_STATE',
      `Gate ${target.id} requires explicit user confirmation.`,
      {
        hint: `Run the gate checks, report the evidence, then re-run with --confirm-gate to mark ${target.id} complete.`,
      },
    );
  }
  if (progress.next?.id?.toUpperCase() !== target.id?.toUpperCase() && !options.force) {
    const nextLabel = progress.next
      ? `${progress.next.id ?? 'unnumbered'} — ${progress.next.text.replace(/[.!?]+$/, '')}`
      : null;
    throw new SpecVibeError('INVALID_STATE', `Task ${target.id} is not the next unchecked item.`, {
      hint: progress.next
        ? `Next: ${nextLabel}. Complete tasks in order, or pass --force.`
        : 'All tasks are complete.',
    });
  }
  const toggled = toggleChecklistItem(tasks, id, true);
  if (!toggled) throw new SpecVibeError('INTERNAL', `Could not update task ${id}.`);
  await writeText(paths.tasks, toggled.content);
  const nextProgress = getTrackProgress(await readText(paths.spec, ''), toggled.content);
  await appendHistory(root, { event: 'task_completed', track: slug, detail: id });
  return { item: toggled.item, progress: nextProgress, next: nextProgress.next };
}

export async function toggleAcceptance(
  root: string,
  slug: string,
  id: string,
): Promise<{ item: ChecklistItem; progress: TrackProgress }> {
  const paths = trackFiles(root, slug);
  const spec = await readText(paths.spec, '');
  const tasks = await readText(paths.tasks, '');
  const target = parseChecklist(spec, 'Acceptance Criteria').find(
    (item) => item.id?.toUpperCase() === id.toUpperCase(),
  );
  if (!target) {
    throw new SpecVibeError('USAGE', `Acceptance criterion "${id}" was not found in spec.md.`, {
      hint: 'Acceptance criteria use IDs such as AC-1.',
    });
  }
  const toggled = toggleChecklistItem(spec, id, true, 'Acceptance Criteria');
  if (!toggled) throw new SpecVibeError('INTERNAL', `Could not update acceptance criterion ${id}.`);
  await writeText(paths.spec, toggled.content);
  const progress = getTrackProgress(toggled.content, tasks);
  await appendHistory(root, { event: 'acceptance_verified', track: slug, detail: id });
  return { item: toggled.item, progress };
}

export function validateTrackDocuments(
  slug: string,
  docs: { proposal: string; spec: string; design: string; tasks: string },
): ValidationResult {
  const issues: ValidationIssue[] = [];
  const files = {
    proposal: docs.proposal,
    spec: docs.spec,
    design: docs.design,
    tasks: docs.tasks,
  };
  for (const [name, content] of Object.entries(files)) {
    const relative = `.specvibe/tracks/${slug}/${name}.md`;
    if (!content.trim()) {
      issues.push({
        severity: 'error',
        code: 'missing_content',
        message: `${name}.md is empty.`,
        file: relative,
      });
      continue;
    }
    const placeholders = findUnresolvedPlaceholders(content);
    for (const placeholder of placeholders) {
      issues.push({
        severity: 'error',
        code: 'unresolved_placeholder',
        message: `Unresolved template variable {{${placeholder}}}.`,
        file: relative,
        line: content.slice(0, content.indexOf(`{{${placeholder}}}`)).split('\n').length,
      });
    }
    const clarifications = content.matchAll(/\[NEEDS CLARIFICATION[^\]]*\]/g);
    for (const match of clarifications) {
      issues.push({
        severity: 'error',
        code: 'needs_clarification',
        message: `Unresolved clarification marker: ${match[0]}`,
        file: relative,
        line: content.slice(0, match.index ?? 0).split('\n').length,
      });
    }
    const plain = content
      .replace(/^#.*$/gm, '')
      .replace(/\[[ xX]\]/g, '')
      .trim();
    if (plain.length < 180) {
      issues.push({
        severity: 'warning',
        code: 'thin_document',
        message: `${name}.md is very short; confirm it contains enough detail for implementation.`,
        file: relative,
      });
    }
  }

  const specSection = findSection(docs.spec, 'Acceptance Criteria');
  if (!specSection) {
    issues.push({
      severity: 'error',
      code: 'missing_acceptance',
      message: 'spec.md must contain an "Acceptance Criteria" section.',
      file: `.specvibe/tracks/${slug}/spec.md`,
    });
  }
  const acceptance = parseChecklist(docs.spec, 'Acceptance Criteria');
  if (acceptance.length === 0) {
    issues.push({
      severity: 'error',
      code: 'no_acceptance',
      message: 'spec.md must contain at least one testable acceptance criterion.',
      file: `.specvibe/tracks/${slug}/spec.md`,
    });
  }
  for (const item of acceptance) {
    if (!item.id) {
      issues.push({
        severity: 'error',
        code: 'acceptance_without_id',
        message: `Acceptance criterion without an ID: "${item.text.slice(0, 60)}".`,
        file: `.specvibe/tracks/${slug}/spec.md`,
        line: item.line,
      });
    }
  }

  const progress = getTrackProgress(docs.spec, docs.tasks);
  if (progress.allTasks.length === 0) {
    issues.push({
      severity: 'error',
      code: 'no_tasks',
      message: 'tasks.md must contain implementation tasks.',
      file: `.specvibe/tracks/${slug}/tasks.md`,
    });
  }
  if (progress.tasks.length === 0) {
    issues.push({
      severity: 'warning',
      code: 'no_implementation_tasks',
      message: 'tasks.md has no tasks with T-prefixed IDs.',
      file: `.specvibe/tracks/${slug}/tasks.md`,
    });
  }
  if (progress.gates.length === 0) {
    issues.push({
      severity: 'error',
      code: 'no_gates',
      message: 'tasks.md must contain at least one verification gate (G-prefixed).',
      file: `.specvibe/tracks/${slug}/tasks.md`,
    });
  }
  const ids = new Map<string, string>();
  for (const item of [...progress.allTasks, ...acceptance]) {
    if (!item.id) continue;
    const key = item.id.toUpperCase();
    if (ids.has(key)) {
      issues.push({
        severity: 'error',
        code: 'duplicate_id',
        message: `Duplicate checklist ID ${key}.`,
        file: `.specvibe/tracks/${slug}/${item.kind === 'acceptance' ? 'spec' : 'tasks'}.md`,
        line: item.line,
      });
    }
    ids.set(key, item.text);
  }

  return {
    valid: issues.every((issue) => issue.severity !== 'error'),
    issues,
    errors: issues.filter((issue) => issue.severity === 'error').length,
    warnings: issues.filter((issue) => issue.severity === 'warning').length,
  };
}

export async function validateTrack(root: string, slug: string): Promise<ValidationResult> {
  const docs = await readTrackDocuments(root, slug);
  return validateTrackDocuments(slug, docs);
}

export async function approveTrack(
  root: string,
  slug: string,
  options: { force?: boolean } = {},
): Promise<{ meta: TrackMeta; validation: ValidationResult }> {
  const meta = await readTrackMeta(root, slug);
  if (meta.status !== 'proposed') {
    throw new SpecVibeError('INVALID_STATE', `Track "${slug}" is ${meta.status}, not proposed.`, {
      hint: 'Only proposed tracks can be approved.',
    });
  }
  const validation = await validateTrack(root, slug);
  if (!validation.valid && !options.force) {
    throw new SpecVibeError(
      'VALIDATION_FAILED',
      `Track "${slug}" has ${validation.errors} validation error(s) and cannot be approved yet.`,
      {
        hint: 'Fix the issues below, or use --force for an intentional exception.',
        details: { issues: validation.issues },
      },
    );
  }
  const next = await updateTrackMeta(root, slug, {
    status: 'approved',
    approvedAt: nowIso(),
    forced: options.force ? true : meta.forced,
  });
  await setActiveTrack(root, slug);
  await appendHistory(root, {
    event: 'approved',
    track: slug,
    detail: options.force ? 'approved with --force' : 'approved',
  });
  return { meta: next, validation };
}

export async function checkpointTrack(
  root: string,
  slug: string,
  checkpoint: TrackCheckpoint,
): Promise<TrackMeta> {
  return updateTrackMeta(root, slug, { checkpoint, status: 'applying', appliedAt: nowIso() });
}

export async function archiveTrack(
  root: string,
  slug: string,
  status: 'unified' | 'reverted',
): Promise<{ archivePath: string; meta: TrackMeta }> {
  const meta = await readTrackMeta(root, slug);
  const date = today();
  let name = `${date}-${slug}`;
  let destination = path.join(projectPaths(root).archive, name);
  let counter = 2;
  while (await pathExists(destination)) {
    name = `${date}-${slug}-${counter}`;
    destination = path.join(projectPaths(root).archive, name);
    counter += 1;
  }
  const next: TrackMeta = {
    ...meta,
    status,
    updatedAt: nowIso(),
    ...(status === 'unified' ? { unifiedAt: nowIso() } : { revertedAt: nowIso() }),
    archivePath: relativePath(root, destination),
  };
  await writeTrackMeta(root, next);
  await moveDirectory(trackDir(root, slug), destination);
  return { archivePath: destination, meta: next };
}

export async function appendDecision(
  root: string,
  entry: {
    title: string;
    slug: string;
    status: 'unified' | 'reverted';
    summary: string;
    decisions: string[];
    archivePath: string;
    forced?: boolean;
  },
): Promise<void> {
  const paths = projectPaths(root);
  let content = await readText(paths.decisions, '');
  if (!content.trim()) {
    content = `# Architectural Decision Log

> Append-only log maintained by SpecVibe. \`specvibe unify\` records shipped decisions here; \`/sv:setup\` may add ratified amendments.

`;
  }
  content = content.replace(/_No decisions recorded yet\._/g, '').trimEnd();
  const decisionLines = entry.decisions.length
    ? entry.decisions.map((decision) => `- ${decision}`).join('\n')
    : '- No new architectural decisions were recorded.';
  const archiveRelative = path.isAbsolute(entry.archivePath)
    ? relativePath(root, entry.archivePath)
    : entry.archivePath;
  const block = `## ${today()} — ${entry.title} (\`${entry.slug}\`)

- **Status:** ${entry.status}${entry.forced ? ' (forced)' : ''}
- **Archive:** \`${archiveRelative}\`
- **Summary:** ${entry.summary.replace(/\s+/g, ' ').slice(0, 500)}

### Decisions

${decisionLines}

`;
  await writeText(paths.decisions, `${content.trimEnd()}\n\n${block}`);
}

export async function extractDecisions(design: string): Promise<string[]> {
  const section = findSection(design, 'Decisions');
  if (!section) return [];
  return section.content
    .split(/\r?\n/)
    .filter((line) => /^\s*(?:[-*+]|\d+\.)\s+/.test(line))
    .map((line) =>
      line
        .replace(/^\s*[-*+]\s+/, '')
        .replace(/^\[[ xX]\]\s*/, '')
        .replace(/^\s*\d+\.\s+/, '')
        .replace(/^\*\*(.*?)\*\*\s*$/, '$1')
        .replace(/^D-\d+\s*[—–:-]\s*/i, '')
        .trim(),
    )
    .filter((line) => line && !line.startsWith('[NEEDS CLARIFICATION') && line !== '...')
    .map((line) => line.replace(/\s+/g, ' '))
    .slice(0, 10);
}

export async function trackHasOpenChecklist(
  root: string,
  slug: string,
): Promise<{
  incompleteTasks: ChecklistItem[];
  uncheckedAcceptance: ChecklistItem[];
  progress: TrackProgress;
}> {
  const docs = await readTrackDocuments(root, slug);
  const progress = getTrackProgress(docs.spec, docs.tasks);
  return {
    incompleteTasks: progress.allTasks.filter((item) => !item.checked),
    uncheckedAcceptance: progress.acceptance.filter((item) => !item.checked),
    progress,
  };
}
