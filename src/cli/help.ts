import type { Logger } from '../core/logger.js';
import { VERSION } from '../version.js';
import { COMMAND_SPECS, GLOBAL_FLAGS } from './specs.js';
import type { CommandSpec, FlagDefinition } from './types.js';

function flagSyntax(flag: FlagDefinition): string {
  const long = `--${flag.name}`;
  const value =
    flag.type === 'boolean' ? '' : flag.placeholder ? ` ${flag.placeholder}` : ' <value>';
  const aliases = (flag.aliases ?? []).length ? `, ${(flag.aliases ?? []).join(', ')}` : '';
  return `${long}${value}${aliases}`;
}

function printFlags(logger: Logger, flags: FlagDefinition[], indent = '  '): void {
  const width = Math.min(34, Math.max(...flags.map((flag) => flagSyntax(flag).length)) + 2);
  for (const flag of flags) {
    logger.write(`${indent}${flagSyntax(flag).padEnd(width)}${flag.description}`);
  }
}

export function printGeneralHelp(logger: Logger): void {
  logger.write(`SpecVibe ${VERSION} — spec-driven governance for AI coding agents`);
  logger.write('');
  logger.write('Usage:');
  logger.write('  specvibe <command> [options]');
  logger.write('  sv <command> [options]');
  logger.write('  npx specvibe <command> [options]');
  logger.write('');
  logger.write('Workflow:');
  const workflow = ['init', 'setup', 'scan', 'propose', 'approve', 'apply', 'unify'];
  for (const name of workflow) {
    const spec = COMMAND_SPECS.find((candidate) => candidate.name === name);
    if (spec) logger.write(`  ${name.padEnd(10)} ${spec.summary}`);
  }
  logger.write('');
  logger.write('Context and maintenance:');
  const maintenance = ['pack', 'status', 'revert', 'agents', 'doctor', 'config'];
  for (const name of maintenance) {
    const spec = COMMAND_SPECS.find((candidate) => candidate.name === name);
    if (spec) logger.write(`  ${name.padEnd(10)} ${spec.summary}`);
  }
  logger.write('');
  logger.write('Agent slash commands (generated by init):');
  logger.write(
    '  OpenCode   /sv/propose   /sv/apply   /sv/unify   (and setup, scan, pack, status, revert)',
  );
  logger.write('  Claude     /sv:propose   /sv:apply   /sv:unify');
  logger.write('  Copilot    /sv-propose   /sv-apply   /sv-unify');
  logger.write('  Cursor     /sv-propose   /sv-apply   /sv-unify   (skills; also .cursor/rules)');
  logger.write('  Windsurf   /sv-propose   /sv-apply   /sv-unify   (workflows)');
  logger.write('  Gemini     /sv:propose   /sv:apply   /sv:unify   (TOML commands)');
  logger.write('');
  logger.write('Global options:');
  printFlags(logger, GLOBAL_FLAGS);
  logger.write('');
  logger.write('Examples:');
  logger.write('  specvibe init');
  logger.write('  specvibe propose "Export invoices as CSV"');
  logger.write('  specvibe approve export-invoices-csv --check');
  logger.write('  specvibe apply export-invoices-csv');
  logger.write('  specvibe status');
  logger.write('');
  logger.write('Run "specvibe help <command>" for command details.');
}

export function printCommandHelp(logger: Logger, spec: CommandSpec): void {
  logger.write(`${spec.summary}`);
  logger.write('');
  logger.write('Usage:');
  logger.write(`  ${spec.usage}`);
  if (spec.aliases?.length) {
    logger.write(`  Aliases: ${spec.aliases.join(', ')}`);
  }
  if (spec.flags.length) {
    logger.write('');
    logger.write('Options:');
    printFlags(logger, spec.flags);
  }
  logger.write('');
  logger.write('Global options:');
  printFlags(logger, GLOBAL_FLAGS);
  if (spec.examples?.length) {
    logger.write('');
    logger.write('Examples:');
    for (const example of spec.examples) logger.write(`  ${example}`);
  }
  if (spec.notes?.length) {
    logger.write('');
    logger.write('Notes:');
    for (const note of spec.notes) logger.write(`  - ${note}`);
  }
}
